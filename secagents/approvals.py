"""The human gate: no containment or eradication step is approved until a person says so.

The Incident Response agent drafts a NIST SP 800-61 playbook. Its Containment and Eradication steps are the ones that
change a live system (block an address, lock an account, delete a user), so each becomes a *proposed action* here.
A security engineer reviews them, may edit the command, and approves or rejects each one; every decision is written
to an audit trail with who, when, and the command before and after any edit.

SecAgents executes nothing. Approving an action marks it ready and puts it into a downloadable runbook script that the
engineer reviews and runs themselves. That keeps the decision and the blame with a person, and means a wrong
suggestion can never change a system by itself.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any

GATED_PHASES = ("Containment", "Eradication")
DECISIONS = ("pending", "approve", "reject")


def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def propose(plan: dict[str, Any]) -> dict[str, Any]:
    """Turn a playbook's containment and eradication steps into actions awaiting a human decision."""
    actions = [{
        "id": f"S{s['step']}", "step": s["step"], "incident": s.get("incident", ""), "phase": s["phase"], "action": s["action"],
        "command": s.get("command", ""), "priority": s.get("priority", ""), "status": "pending", "approved_command": "",
        "decided_by": "", "decided_at": "",
    } for s in plan.get("steps", []) if s.get("phase") in GATED_PHASES]
    return {"status": "pending_approval" if actions else "none", "executes": False, "actions": actions, "audit": []}


def overall_status(actions: list[dict[str, Any]]) -> str:
    if not actions:
        return "none"
    states = {a["status"] for a in actions}
    if states == {"pending"}:
        return "pending_approval"
    if "pending" in states:
        return "in_review"
    if states == {"approved"}:
        return "approved"
    if states == {"rejected"}:
        return "rejected"
    return "decided"  # a mix of approved and rejected, nothing left pending


def counts(gate: dict[str, Any]) -> dict[str, int]:
    acts = gate.get("actions", [])
    return {s: sum(1 for a in acts if a["status"] == s) for s in ("pending", "approved", "rejected")}


def decide(gate: dict[str, Any], decisions: dict[str, dict[str, str]], who: str, now: str | None = None) -> dict[str, Any]:
    """Apply a person's decisions: ``{action id: {"decision": "approve"|"reject"|"pending", "command": edited command}}``.

    Returns a new gate. Unknown ids and bad decisions raise ValueError; a command may not contain a line break (what the
    reviewer sees on one line must be the one command that goes into the runbook). Only real changes are audited.
    """
    when = now or _now()
    by_id = {a["id"]: a for a in gate.get("actions", [])}
    for aid, d in decisions.items():
        if aid not in by_id:
            raise ValueError(f"unknown action {aid!r}")
        if d.get("decision", "pending") not in DECISIONS:
            raise ValueError(f"decision for {aid} must be one of {', '.join(DECISIONS)}")
        cmd = d.get("command", "")
        if any(ch in cmd for ch in "\r\n\x00"):
            raise ValueError(f"the command for {aid} must be a single line")
    new = {**gate, "actions": [dict(a) for a in gate.get("actions", [])], "audit": list(gate.get("audit", []))}
    for a in new["actions"]:
        d = decisions.get(a["id"])
        if not d:
            continue
        status = {"approve": "approved", "reject": "rejected", "pending": "pending"}[d.get("decision", "pending")]
        command = (d.get("command") if d.get("command") is not None else a["command"]).strip()
        before_cmd = a["approved_command"] or a["command"]
        if status == a["status"] and (status != "approved" or command == a["approved_command"]):
            continue
        new["audit"].append({"at": when, "by": who, "action": a["id"], "decision": status, "from": a["status"],
                             "command_before": before_cmd, "command_after": command if status == "approved" else ""})
        a["status"] = status
        a["approved_command"] = command if status == "approved" else ""
        a["decided_by"], a["decided_at"] = (who, when) if status != "pending" else ("", "")
    new["status"] = overall_status(new["actions"])
    return new


def runbook(gate: dict[str, Any], title: str = "Containment runbook", who: str = "") -> str:
    """A shell script of the approved commands only. It is generated for a person to review and run; the app never runs it."""
    approved = [a for a in gate.get("actions", []) if a["status"] == "approved"]
    lines = [
        "#!/usr/bin/env bash",
        f"# {title}",
        "# Generated by SecAgents from actions a person approved. SecAgents did NOT run any of this.",
        "# Read every line, check it matches your environment, and run it yourself (with a rollback plan).",
        f"# Exported {_now()}" + (f" by {who}" if who else ""),
        "",
    ]
    if not approved:
        lines.append("# No actions have been approved yet.")
    for a in approved:
        lines += [f"# [{a['id']}] {a['incident']} · {a['phase']} · {a['priority']}: {a['action']}",
                  f"# approved by {a['decided_by']} at {a['decided_at']}"]
        lines.append(a["approved_command"] if a["approved_command"] else "# (no command: carry out this step manually)")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"
